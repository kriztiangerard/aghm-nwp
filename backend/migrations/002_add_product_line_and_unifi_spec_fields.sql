-- NWP-SETUP-007
-- Add product line relationships and missing device specification fields.
--
-- Depends on: 001_initial_schema.sql

BEGIN;

-- 1. Product line table
CREATE TABLE IF NOT EXISTS product_line (
    product_line_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id INT NOT NULL,
    category TEXT NOT NULL,
    name TEXT NOT NULL,
    line_rank INT NOT NULL,
    source_note TEXT NOT NULL,

    CONSTRAINT product_line_vendor_id_fkey
        FOREIGN KEY (vendor_id)
        REFERENCES vendor(vendor_id),

    CONSTRAINT product_line_category_check
        CHECK (category IN ('gateway_router', 'ap', 'switch')),

    CONSTRAINT product_line_line_rank_check
        CHECK (line_rank >= 1),

    CONSTRAINT product_line_name_check
        CHECK (length(name) > 0),

    CONSTRAINT product_line_name_unique
        UNIQUE (vendor_id, category, name),

    CONSTRAINT product_line_rank_unique
        UNIQUE (vendor_id, category, line_rank)
        DEFERRABLE
);

-- 2. Add product line reference to devices
ALTER TABLE device
    ADD COLUMN IF NOT EXISTS product_line_id INT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'device_product_line_id_fkey'
          AND conrelid = 'public.device'::regclass
    ) THEN
        ALTER TABLE device
            ADD CONSTRAINT device_product_line_id_fkey
            FOREIGN KEY (product_line_id)
            REFERENCES product_line(product_line_id);
    END IF;
END $$;

-- 3. Add gateway router HA capability
ALTER TABLE gateway_router_specifications
    ADD COLUMN IF NOT EXISTS ha_capability BOOLEAN NULL;

-- 4. Add firewall IDPS throughput
ALTER TABLE firewall_specifications
    ADD COLUMN IF NOT EXISTS idps_throughput_mbps INT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'firewall_specifications_idps_throughput_mbps_check'
          AND conrelid = 'public.firewall_specifications'::regclass
    ) THEN
        ALTER TABLE firewall_specifications
            ADD CONSTRAINT firewall_specifications_idps_throughput_mbps_check
            CHECK (idps_throughput_mbps >= 0);
    END IF;
END $$;

-- 5. Add vendor + SKU uniqueness for device upserts
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'device_vendor_sku_unique'
          AND conrelid = 'public.device'::regclass
    ) THEN
        ALTER TABLE device
            ADD CONSTRAINT device_vendor_sku_unique
            UNIQUE (vendor_id, sku);
    END IF;
END $$;

COMMIT;
